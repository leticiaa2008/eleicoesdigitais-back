create table if not exists public.election_settings (
 id integer primary key check (id = 1), title text not null default 'Clube de Esportes',
 description text not null default 'Eleição simulada para escolher prioridades esportivas da instituição.',
 is_open boolean not null default true, created_at timestamptz not null default now()
);
insert into public.election_settings (id,title,description,is_open) values (1,'Clube de Esportes','Eleição simulada para escolher prioridades esportivas da instituição.',true) on conflict (id) do nothing;
create table if not exists public.candidates (
 id bigint generated by default as identity primary key, number integer not null unique,
 name text not null, slogan text not null default '', photo_url text, created_at timestamptz not null default now()
);
create table if not exists public.proposals (
 id bigint generated by default as identity primary key, candidate_id bigint not null references public.candidates(id) on delete cascade,
 title text not null, description text not null, created_at timestamptz not null default now()
);
create table if not exists public.votes (
 id bigint generated by default as identity primary key, election_id integer not null default 1 references public.election_settings(id),
 candidate_id bigint not null references public.candidates(id), voter_key text not null, created_at timestamptz not null default now(),
 constraint votes_one_per_session unique (election_id, voter_key)
);
create index if not exists proposals_candidate_id_idx on public.proposals(candidate_id);
create index if not exists votes_candidate_id_idx on public.votes(candidate_id);
create table if not exists public.election_events (
 id bigint generated by default as identity primary key, title text not null, message text not null, created_at timestamptz not null default now()
);
alter table public.election_settings enable row level security;
alter table public.candidates enable row level security;
alter table public.proposals enable row level security;
alter table public.votes enable row level security;
alter table public.election_events enable row level security;
